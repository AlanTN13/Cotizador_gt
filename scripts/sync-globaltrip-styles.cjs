// Build the original site's CSS in an isolated scope. Never apply its Tailwind
// preflight/theme to the quote form, which uses a different Tailwind version.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'components/globaltrip/styles/source/site-2026-09-11.css'), 'utf8');
const components = ['Header', 'Footer', 'NewsletterSignup'].map(name =>
  fs.readFileSync(path.join(root, `components/globaltrip/components/${name}.jsx`), 'utf8')
).join('\n');
const scope = '[data-globaltrip-chrome]';
// SVG presentation attributes (especially path d) belong to the author origin;
// reverting all properties would erase the original social icon shapes.
const output = postcss.parse(`${scope}, ${scope} *:not(svg, svg *) { all: revert; }`);

function scopedSelector(selector) {
  return postcss.list.comma(selector).flatMap(s => {
    if (['html', 'body', ':root', ':host'].includes(s)) return [scope];
    return [`${scope}:is(${s})`, `${scope} ${s}`];
  }).join(',');
}

// Compiled utilities are one escaped class followed by optional pseudo-classes.
// Keep all dynamic variants that occur in the original JSX, including mobile,
// language selection, loading and validation states.
function usedUtility(rule) {
  const match = rule.selector.match(/^\.((?:\\.|[^\s:.,>+~])+)/);
  if (!match) return false;
  const className = match[1].replace(/\\(.)/g, '$1');
  return components.includes(className);
}

function add(node, destination, mode) {
  if (node.type === 'atrule') {
    if (node.name === 'layer') {
      if (['theme', 'base', 'utilities', 'properties'].includes(node.params)) {
        for (const child of node.nodes || []) add(child, destination, node.params);
      }
      return;
    }
    if (node.name === 'property') { destination.append(node.clone()); return; }
    if (node.name === 'keyframes' && node.params === 'spin') {
      destination.append(node.clone({ params: 'globaltrip-spin' }));
      return;
    }
    if (!['media', 'supports'].includes(node.name)) return;
    // Custom global media rules are limited to the site's cursor rule.
    if (!mode && node.params !== '(pointer:fine)') return;
    const copy = node.clone({ nodes: [] });
    for (const child of node.nodes || []) add(child, copy, mode);
    if (copy.nodes.length) destination.append(copy);
    return;
  }
  if (node.type !== 'rule') return;
  if (mode === 'utilities' && !usedUtility(node)) return;
  if (!mode && node.selector !== '.material-symbols-outlined' && !node.selector.includes(':before')) return;
  const copy = node.clone();
  copy.selector = scopedSelector(copy.selector);
  destination.append(copy);
}

const original = postcss.parse(source);
for (const node of original.nodes) add(node, output);
output.append(postcss.parse(`${scope} { font-family: "GlobalTrip Manrope", sans-serif; line-height: 1.5; color: oklch(20.8% .042 265.755); -webkit-font-smoothing: antialiased; }`).nodes);

// Namespace Tailwind 4 custom properties, including registrations, so its
// transforms/rings cannot interact with the form's Tailwind 3 variables.
const css = output.toString().replace(/--([a-zA-Z][\w-]*)/g, '--gt-$1')
  .replace(/(--gt-animate-spin:\s*)spin\b/g, '$1globaltrip-spin')
  .replaceAll('/avion-2-cursor.png', '/brand/avion-2-cursor.png');
fs.writeFileSync(path.join(root, 'components/globaltrip/styles/chrome.css'),
  '/* Generated by scripts/sync-globaltrip-styles.cjs from the original published GlobalTrip stylesheet. */\n' + css);
